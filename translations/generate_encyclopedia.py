"""Generate native encyclopedia text data from the pinned GAME.NFO and authored prose.

This is a data authoring command, not a game runner. Source ranges describe
semantic passages in the asset; they are unrelated to screen rows or geometry.
Usage: python3 translations/generate_encyclopedia.py /path/to/GAME.NFO
"""
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1]).read_bytes().splitlines(keepends=True)

def rows(name):
    for line in (root / 'translations' / name).read_text().splitlines():
        if line and not line.startswith('#'):
            yield line.split('\t', 1)

titles = {int(k): v for k, v in rows('encyclopedia-titles.zh-CN.tsv')}
labels = dict(rows('encyclopedia-aliases.zh-CN.tsv'))
passages = {}
for interval, text in rows('encyclopedia.zh-CN.tsv'):
    ends = list(map(int, interval.split('-')))
    for line in range(ends[0], ends[-1] + 1):
        passages[line] = text if line == ends[0] else ''

# Retain the published culture topic IDs and keys across business hot reload.
old = {118:'cultures',285:'eastern_peoples',290:'western_peoples',297:'kaumo',
       318:'kiesse',336:'driik',355:'reemi',368:'sartola',386:'islanders',
       396:'koivula',410:'northern_peoples',427:'kuikka_tribe',435:'owl_tribe',
       445:'seal_tribe',456:'njerpez',467:'language',478:'language_inflexions'}

def native_upper(text):
    values = text.encode('cp437')
    return bytes(0xc4 if b in (0x84,0x8e,0xe4) else
                 0xd6 if b in (0x94,0x99,0xf6) else
                 b-32 if 97 <= b <= 122 else b for b in values)

def literal(data):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34,92)
                         else '\\%03o' % b for b in data) + '"'

catalog = root / 'catalog/zh-CN/cultures.tsv'
retained = [line for line in catalog.read_text().splitlines()
            if line.startswith(('culture.ui.', 'culture.map.')) or
            line.startswith('culture.topic.') and
            line.split('.')[2] in old.values()]
output = ['# Generated by translations/generate_encyclopedia.py; UTF-8.',
          '# GAME.NFO SHA-256: 071f384ad992d0a688833693f207a5cf8a969b4811e5e6603597d189087a4d5d',
          '# record keys are FILE offsets AFTER native fgets(150), including comment skipping.',
          '# Empty translations are explicit continuations of a complete authored passage.'] + retained
new_topics = ['// Generated native topic aliases; published culture IDs precede these.']
links = ['// Generated complete native topic names and display label keys.']
seen = set()
active = False
picture = False
position = 0
records = 0
for number, raw in enumerate(source, 1):
    start = position
    position += len(raw)
    text = raw.decode('cp437').strip()
    if text.startswith('.') and text.endswith('.'):
        active = True
        key = old[number] if number in old else 'encyclopedia_' + str(number)
        if number not in old:
            output.append('culture.topic.' + key + '.title\t' + titles[number])
        for index, alias in enumerate(text[1:-1].split('.')):
            name = native_upper(alias)
            if name in seen:
                continue
            seen.add(name)
            label_key = str(number) + '_' + str(index)
            label = labels[alias] if alias in labels else titles[number]
            output.append('culture.link.' + label_key + '\t' + label)
            links.append('    {' + literal(name) + ',"' + label_key + '"},')
            if number not in old:
                new_topics.append('    {' + literal(name) + ',"' + key + '"},')
        continue
    if text.startswith('***'):
        active = False
        continue
    if text.startswith(('//', '##')) or not active:
        continue
    if picture:
        picture = False
        continue
    if text.startswith('%'):
        picture = True
        continue
    translation = text if text in ('', '<br>', '<bt>') else passages[number]
    # fgets(150) consumes up to 149 bytes, including CR/LF when they fit.
    for offset in range(0, len(raw), 149):
        end = start + min(offset + 149, len(raw))
        output.append('culture.record.' + str(end) + '\t' + (translation if offset == 0 else ''))
        records += 1

catalog.write_text('\n'.join(output) + '\n')
(root / 'src/linux/encyclopedia_topics.inc').write_text('\n'.join(new_topics) + '\n')
(root / 'src/linux/encyclopedia_links.inc').write_text('\n'.join(links) + '\n')
print(f'Generated {len(titles)} source topic records, {len(seen)} aliases, {records} native text records.')
