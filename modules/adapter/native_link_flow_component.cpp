std::vector<ActionSourceRow> actions(MenuHandle owner,const native_menu_model::MenuModel& value) {
    std::vector<ActionSourceRow> rows;
    for(u32 index=0;index<scalar(value.header.data(),row_count);++index) {
        const auto* row=value.rows.data()+index*native_menu_model::row_stride;
        // 3D6CA writes zero for link rows. CFAF0 writes its original nonzero
        // action at CFBD4, independently of the localized display label.
        if(scalar(row,row_action)) {
            const auto& label=native_menu_model::row(owner,index);
            const auto& annotation=native_menu_model::annotation(owner,index);
            ActionSourceRow copy;std::memcpy(copy.native.data(),row,copy.native.size());
            copy.label=label.source;copy.prefix=label.prefix;copy.annotation=annotation.source;
            rows.push_back(std::move(copy));
        }
    }
    return rows;
}
void consume(Handle handle,const Record& record,const std::vector<std::string>& fragments,u32& native_return) {
    using Show=u32 (__fastcall *)(const char*,const char*);
    const auto show=reinterpret_cast<Show>(base+0x3D820);
    services.enter(handle,record);
    // Empty translated continuation records deliberately make no native call.
    // Original blank/control records provide one empty fragment instead.
    native_return=native(flow_y);
    for(const auto& fragment:fragments)
        native_return=show(fragment.c_str(),record.exclusions.c_str());
    services.leave(handle);
    capture(handle);
}
Status consume(Handle handle,const Record& record,u32& native_return) {
    std::vector<std::string> fragments;
    const auto status=services.prepare(record,fragments);
    if(status!=Status::ok) return status;
    consume(handle,record,fragments,native_return);
    return Status::ok;
}

