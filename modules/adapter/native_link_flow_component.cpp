u32 action_row(Handle handle,u32 action) {
    const auto previous=native_menu_component::active();
    if(previous) native_menu_component::retain(previous);
    native_menu_component::activate(menu_owner(handle));
    const auto count=native(header_rva+row_count);
    u32 index{};
    for(;index<count;++index)
        if(native(rows_rva+index*native_menu_model::row_stride+row_action)==action) break;
    if(previous) { native_menu_component::activate(previous);native_menu_component::release(previous); }
    else native_menu_component::deactivate();
    return index;
}
void retain(Handle handle) { ++models.find(handle)->second.references; }
void release(Handle handle) {
    const auto instance=models.find(handle);
    if(--instance->second.references==0) {
        const auto owner=instance->second.input_owner;
        native_menu_component::release(instance->second.menu);models.erase(instance);
        if(owner!=handle) release(owner);
    }
}
Handle snapshot(Handle handle) {
    auto& original=models.find(handle)->second;
    if(native_menu_component::input_owner(original.menu)==native_menu_component::active()) capture(handle);
    auto copy=original;copy.references=1;
    retain(copy.input_owner);
    copy.menu=native_menu_component::snapshot(original.menu);
    const auto copied=next_handle++;models.emplace(copied,std::move(copy));return copied;
}
Status paint(Handle handle) {
    auto& instance=models.find(handle)->second;
    auto& input=models.find(instance.input_owner)->second;
    // Resolve the complete component's temporary native input arguments before
    // entering its mutable native Menu view. No encoded text enters the model.
    std::vector<std::vector<std::string>> arguments;
    for(const auto& record:instance.source.records) {
        arguments.emplace_back();
        const auto status=services.prepare(record,arguments.back());
        if(status!=Status::ok) return status;
    }
    const auto previous=native_menu_component::active();
    const auto caller_context=context();const auto caller_links=links();
    const auto caller_x=native(cursor_x),caller_y=native(cursor_y);
    if(previous) native_menu_component::retain(previous);
    native_menu_component::activate(instance.menu);
    const auto selected=native(header_rva+selection);
    const auto action=native(rows_rva+selected*native_menu_model::row_stride+row_action);
    const std::string topic=action ? "" : input.links.names.data()+(selected+2)*link_stride;

    // Keep the latest owned header input fields. Only its row construction
    // count returns to the native builder's source prefix before link layout.
    native(header_rva+row_count)=static_cast<u32>(instance.seed_rows.size());
    for(std::size_t row=0;row<instance.seed_rows.size();++row)
        std::memcpy(reinterpret_cast<void*>(base+rows_rva+row*native_menu_model::row_stride),
            instance.seed_rows[row].data(),native_menu_model::row_stride);
    install(instance.origin);install(instance.seed_links);
    for(std::size_t record=0;record<instance.source.records.size();++record) {
        u32 native_return;
        consume(handle,instance.source.records[record],arguments[record],native_return);
    }
    const auto link_rows=native(header_rva+row_count);
    for(const auto& row:instance.actions) {
        auto& count=native(header_rva+row_count);
        std::memcpy(reinterpret_cast<void*>(base+rows_rva+count*native_menu_model::row_stride),row.native.data(),row.native.size());
        // The native link builder can change the number of preceding rows.
        // Move each independent action's neutral resources with its native
        // action identity, including an explicitly empty original annotation.
        const auto owner=native_menu_component::input_owner(instance.menu);
        native_menu_model::bind_row(owner,count,row.label,row.prefix);
        native_menu_model::bind_annotation(owner,count,row.annotation);
        ++count;
    }
    if(action) {
        const auto row=std::find_if(instance.actions.begin(),instance.actions.end(),
            [action](const ActionSourceRow& row){return scalar(row.native.data(),row_action)==action;});
        native(header_rva+selection)=link_rows+static_cast<u32>(row-instance.actions.begin());
    } else {
        u32 row{};
        for(;row<link_rows;++row)
            if(topic==input.links.names.data()+(row+2)*link_stride) break;
        native(header_rva+selection)=row;
    }
    capture(handle);
    if(previous) { native_menu_component::activate(previous);native_menu_component::release(previous); }
    else native_menu_component::deactivate();
    if(previous!=native_menu_component::input_owner(instance.menu)) {
        install(caller_context);install(caller_links);native(cursor_x)=caller_x;native(cursor_y)=caller_y;
    }
    return Status::ok;
}
std::vector<std::uint8_t> save() {
    Writer output;output.value(next_handle);output.value(active_handle);output.value(static_cast<u32>(models.size()));
    for(const auto& [handle,instance]:models) {
        output.value(handle);output.value(instance.references);output.value(instance.input_owner);
        output.key(instance.source.key);output.string(instance.source.topic);
        output.context(instance.origin);output.value(static_cast<u32>(instance.seed_rows.size()));
        for(const auto& row:instance.seed_rows) output.plain(row.data(),row.size());
        output.links(instance.seed_links);
        output.value(instance.menu);output.links(instance.links);output.value(static_cast<u32>(instance.actions.size()));
        for(const auto& row:instance.actions) {
            output.plain(row.native.data(),row.native.size());
            output.text(row.label);output.string(row.prefix);output.text(row.annotation);
        }
        output.value(static_cast<u32>(instance.source.records.size()));
        for(const auto& record:instance.source.records) {
            output.value(record.native_record);output.text(record.text);output.string(record.native_original);output.string(record.exclusions);
        }
    }
    return std::move(output.bytes);
}
void restore(const void* payload) {
    Reader input{static_cast<const std::uint8_t*>(payload)};
    next_handle=input.value<u32>();active_handle=input.value<u32>();const auto count=input.value<u32>();models.clear();
    for(u32 index=0;index<count;++index) {
        const auto handle=input.value<u32>();Instance instance{};instance.references=input.value<u32>();
        instance.input_owner=input.value<u32>();
        instance.source.key=input.key();instance.source.topic=input.string();instance.origin=input.context();
        const auto prefix_count=input.value<u32>();
        for(u32 row=0;row<prefix_count;++row) { NativeActionRow value;input.plain(value.data(),value.size());instance.seed_rows.push_back(value); }
        instance.seed_links=input.links();instance.menu=input.value<u32>();instance.links=input.links();
        const auto action_count=input.value<u32>();
        for(u32 row=0;row<action_count;++row) {
            ActionSourceRow action;input.plain(action.native.data(),action.native.size());
            action.label=input.text();action.prefix=input.string();action.annotation=input.text();
            instance.actions.push_back(std::move(action));
        }
        const auto record_count=input.value<u32>();
        for(u32 row=0;row<record_count;++row) {
            const auto native_record=input.value<u64>();auto text=input.text();auto native_original=input.string(),exclusions=input.string();
            instance.source.records.push_back({native_record,std::move(text),std::move(native_original),std::move(exclusions)});
        }
        models.emplace(handle,std::move(instance));
    }
}
