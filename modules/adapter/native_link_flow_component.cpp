void initialize(std::uintptr_t image_base) {
    base=image_base;services={};next_handle=1;active_handle=0;models.clear();
}
void configure(const Services& value) { services=value; }
Handle begin(native_text_resource::SourceKey key,const char* topic) {
    deactivate();
    const auto handle=next_handle++;
    const auto owner=native_menu_component::active();
    native_menu_component::retain(owner);
    const auto initial_links=links();
    // The confirmed 3DF74 builder has a newly constructed menu with no link
    // rows. Retain only its actual counted source prefix, never unused bytes
    // left in the shared native array by a preceding topic.
    std::vector<NativeActionRow> initial_rows;
    for(u32 row=0;row<native(header_rva+row_count);++row) {
        NativeActionRow value;
        std::memcpy(value.data(),reinterpret_cast<const void*>(base+rows_rva+row*value.size()),value.size());
        initial_rows.push_back(value);
    }
    models.emplace(handle,Instance{1,{key,topic,{}},context(),std::move(initial_rows),initial_links,owner,initial_links,{},handle});
    active_handle=handle;
    return handle;
}
Handle active() { return active_handle; }
Handle input_owner(Handle handle) { return models.find(handle)->second.input_owner; }
void activate(Handle handle) {
    handle=input_owner(handle);
    if(active_handle && native_menu_component::input_owner(menu_owner(active_handle))==native_menu_component::active()) capture(active_handle);
    retain(handle);
    const auto previous=active_handle;active_handle=handle;
    native_menu_component::activate(menu_owner(handle));install(models.find(handle)->second.links);
    if(previous) release(previous);
}
void deactivate() {
    const auto previous=active_handle;active_handle=0;
    if(previous) release(previous);
}
std::size_t append(Handle handle,u64 native_record,const native_text_resource::TextSource& text,
    const char* native_original,const char* exclusions) {
    auto& records=models.find(handle)->second.source.records;
    records.push_back({native_record,text,native_original,exclusions});return records.size()-1;
}
Status consume(Handle handle,std::size_t record,u32& native_return) {
    return consume(handle,models.find(handle)->second.source.records[record],native_return);
}
void capture(Handle handle) {
    auto& instance=models.find(input_owner(handle))->second;
    instance.links=links();native_menu_model::capture_into(instance.menu);
}
void seal(Handle handle) {
    capture(handle);
    auto& instance=models.find(handle)->second;
    instance.actions=actions(native_menu_component::input_owner(instance.menu),menu());
}
const Source& source(Handle handle) { return models.find(handle)->second.source; }
